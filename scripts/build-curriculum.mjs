import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { CLUSTER_1_EPISTEMOLOGY } from './curriculum-data/cluster1-epistemology.mjs';
import { CLUSTER_2_CRITICAL_THEORY } from './curriculum-data/cluster2-critical-theory.mjs';
import { CLUSTER_3_LITERARY_CRITICISM } from './curriculum-data/cluster3-literary-criticism.mjs';
import { CLUSTER_4_POETICS_RHETORIC } from './curriculum-data/cluster4-poetics-rhetoric.mjs';
import { CLUSTER_5_AESTHETICS_EXISTENTIALISM } from './curriculum-data/cluster5-aesthetics-existentialism.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const ALL_100_TERMS = [
  ...CLUSTER_1_EPISTEMOLOGY,
  ...CLUSTER_2_CRITICAL_THEORY,
  ...CLUSTER_3_LITERARY_CRITICISM,
  ...CLUSTER_4_POETICS_RHETORIC,
  ...CLUSTER_5_AESTHETICS_EXISTENTIALISM,
];

if (ALL_100_TERMS.length !== 100) {
  throw new Error(`Expected exactly 100 terms, but found ${ALL_100_TERMS.length}`);
}

// Check for unique terms
const seen = new Set();
for (const item of ALL_100_TERMS) {
  const t = item.term.toLowerCase();
  if (seen.has(t)) {
    throw new Error(`Duplicate term detected in curriculum: ${t}`);
  }
  seen.add(t);
}

console.log(`Validated ${ALL_100_TERMS.length} unique terms across 5 intellectual clusters.`);

// Helper to format deterministic UUIDs: 00000000-0000-0000-0000-000000000001 ... 000000000100
function getDeterministicUuid(index) {
  const hex = (index + 1).toString().padStart(4, '0');
  return `00000000-0000-0000-0000-00000000${hex}`;
}

const DEFAULT_USER_ID = '00000000-0000-0000-0000-000000000000';
const BASE_TIMESTAMP = '2026-10-15T12:00:00.000Z';
const BASE_DATE = new Date(BASE_TIMESTAMP);

// 1. Generate lib/db/philosophical-seed-data.ts
console.log('Generating lib/db/philosophical-seed-data.ts...');

const cardsCode = ALL_100_TERMS.map((termData, idx) => {
  const cardId = getDeterministicUuid(idx);
  const batchIndex = Math.floor(idx / 10); // 0 to 9
  
  // Staggered due date:
  // Batch 0 is due immediately (now - 2 hours); Batch 1 is due +1 day; ... Batch 9 is due +9 days
  let dueDate;
  let state = 0; // New
  let reps = 0;
  let stability = 0;
  let difficulty = 0;
  let lastReview = null;

  if (batchIndex === 0) {
    // Due now for immediate learning
    dueDate = new Date(BASE_DATE.getTime() - 2 * 60 * 60 * 1000).toISOString();
  } else {
    dueDate = new Date(BASE_DATE.getTime() + batchIndex * 24 * 60 * 60 * 1000).toISOString();
  }

  const cardObj = {
    id: cardId,
    user_id: DEFAULT_USER_ID,
    term: termData.term,
    language: 'en',
    part_of_speech: termData.part_of_speech,
    phonetic: termData.phonetic,
    primary_definition: termData.primary_definition,
    nuance_note: termData.nuance_note,
    etymology: termData.etymology,
    collocations: termData.collocations,
    source_context: {
      sentence: termData.source_context.sentence,
      source: termData.source_context.source,
      author: termData.source_context.author || null,
    },
    cloze_sentences: termData.cloze_sentences,
    distinction_matrix: termData.distinction_matrix,
    is_fallback: false,
    enrichment_source: 'curated',
    created_at: BASE_TIMESTAMP,
    srs: {
      card_id: cardId,
      user_id: DEFAULT_USER_ID,
      due: dueDate,
      stability,
      difficulty,
      elapsed_days: 0,
      scheduled_days: batchIndex,
      reps,
      lapses: 0,
      state,
      last_review: lastReview,
    },
  };

  return JSON.stringify(cardObj, null, 2);
}).join(',\n');

const tsFileContent = `// Auto-generated by scripts/build-curriculum.mjs. Do not edit manually.
import { CardWithSrs } from '@/types/lexis';
import { DEFAULT_USER_ID } from './seed-data';

export { DEFAULT_USER_ID };

export const PHILOSOPHICAL_SEED_CARDS: CardWithSrs[] = [
${cardsCode}
];

export function getPhilosophicalSeedCards(userId: string = DEFAULT_USER_ID): CardWithSrs[] {
  return PHILOSOPHICAL_SEED_CARDS.map(c => ({
    ...c,
    user_id: userId,
    srs: {
      ...c.srs,
      user_id: userId,
    },
  }));
}
`;

const tsPath = path.join(projectRoot, 'lib', 'db', 'philosophical-seed-data.ts');
fs.writeFileSync(tsPath, tsFileContent, 'utf-8');
console.log(`Wrote ${tsPath} (${(fs.statSync(tsPath).size / 1024).toFixed(1)} KB)`);

// 2. Generate supabase/seed.sql
console.log('Generating supabase/seed.sql...');

function sqlEscapeString(str) {
  if (str === null || str === undefined) return 'NULL';
  return `'${String(str).replace(/'/g, "''")}'`;
}

function sqlEscapeJson(obj) {
  if (obj === null || obj === undefined) return 'NULL';
  const jsonStr = JSON.stringify(obj).replace(/'/g, "''");
  return `'${jsonStr}'::jsonb`;
}

function sqlEscapeArray(arr) {
  if (!arr || !Array.isArray(arr) || arr.length === 0) return 'ARRAY[]::text[]';
  const elements = arr.map(item => sqlEscapeString(item)).join(', ');
  return `ARRAY[${elements}]`;
}

const sqlLines = [];
sqlLines.push('-- ============================================================================');
sqlLines.push('-- Lexis Engine: 100-Term Philosophical & Literary Foundational Seed (PostgreSQL)');
sqlLines.push('-- Generated on: ' + new Date().toISOString());
sqlLines.push('-- Idempotent: Can be run multiple times safely via ON CONFLICT');
sqlLines.push('-- ============================================================================');
sqlLines.push('');
sqlLines.push('BEGIN;');
sqlLines.push('');

for (let i = 0; i < ALL_100_TERMS.length; i++) {
  const termData = ALL_100_TERMS[i];
  const cardId = getDeterministicUuid(i);
  const batchIndex = Math.floor(i / 10);
  
  let dueDate;
  if (batchIndex === 0) {
    dueDate = new Date(BASE_DATE.getTime() - 2 * 60 * 60 * 1000).toISOString();
  } else {
    dueDate = new Date(BASE_DATE.getTime() + batchIndex * 24 * 60 * 60 * 1000).toISOString();
  }

  const sourceContext = {
    sentence: termData.source_context.sentence,
    source: termData.source_context.source,
    author: termData.source_context.author || null,
  };

  sqlLines.push(`-- Card ${i + 1}: ${termData.term}`);
  sqlLines.push(`INSERT INTO vocab_cards (`);
  sqlLines.push(`    id, user_id, term, language, part_of_speech, phonetic,`);
  sqlLines.push(`    primary_definition, nuance_note, etymology, collocations,`);
  sqlLines.push(`    source_context, cloze_sentences, distinction_matrix,`);
  sqlLines.push(`    is_fallback, enrichment_source, created_at`);
  sqlLines.push(`) VALUES (`);
  sqlLines.push(`    ${sqlEscapeString(cardId)},`);
  sqlLines.push(`    ${sqlEscapeString(DEFAULT_USER_ID)},`);
  sqlLines.push(`    ${sqlEscapeString(termData.term)},`);
  sqlLines.push(`    'en',`);
  sqlLines.push(`    ${sqlEscapeString(termData.part_of_speech)},`);
  sqlLines.push(`    ${sqlEscapeString(termData.phonetic)},`);
  sqlLines.push(`    ${sqlEscapeString(termData.primary_definition)},`);
  sqlLines.push(`    ${sqlEscapeString(termData.nuance_note)},`);
  sqlLines.push(`    ${sqlEscapeJson(termData.etymology)},`);
  sqlLines.push(`    ${sqlEscapeArray(termData.collocations)},`);
  sqlLines.push(`    ${sqlEscapeJson(sourceContext)},`);
  sqlLines.push(`    ${sqlEscapeArray(termData.cloze_sentences)},`);
  sqlLines.push(`    ${sqlEscapeJson(termData.distinction_matrix)},`);
  sqlLines.push(`    false,`);
  sqlLines.push(`    'curated',`);
  sqlLines.push(`    ${sqlEscapeString(BASE_TIMESTAMP)}`);
  sqlLines.push(`) ON CONFLICT (id) DO UPDATE SET`);
  sqlLines.push(`    term = EXCLUDED.term,`);
  sqlLines.push(`    part_of_speech = EXCLUDED.part_of_speech,`);
  sqlLines.push(`    phonetic = EXCLUDED.phonetic,`);
  sqlLines.push(`    primary_definition = EXCLUDED.primary_definition,`);
  sqlLines.push(`    nuance_note = EXCLUDED.nuance_note,`);
  sqlLines.push(`    etymology = EXCLUDED.etymology,`);
  sqlLines.push(`    collocations = EXCLUDED.collocations,`);
  sqlLines.push(`    source_context = EXCLUDED.source_context,`);
  sqlLines.push(`    cloze_sentences = EXCLUDED.cloze_sentences,`);
  sqlLines.push(`    distinction_matrix = EXCLUDED.distinction_matrix;`);
  sqlLines.push('');
  sqlLines.push(`INSERT INTO srs_cards (`);
  sqlLines.push(`    card_id, user_id, due, stability, difficulty,`);
  sqlLines.push(`    elapsed_days, scheduled_days, reps, lapses, state, last_review`);
  sqlLines.push(`) VALUES (`);
  sqlLines.push(`    ${sqlEscapeString(cardId)},`);
  sqlLines.push(`    ${sqlEscapeString(DEFAULT_USER_ID)},`);
  sqlLines.push(`    ${sqlEscapeString(dueDate)},`);
  sqlLines.push(`    0, 0, 0, ${batchIndex}, 0, 0, 0, NULL`);
  sqlLines.push(`) ON CONFLICT (card_id) DO UPDATE SET`);
  sqlLines.push(`    due = EXCLUDED.due,`);
  sqlLines.push(`    scheduled_days = EXCLUDED.scheduled_days;`);
  sqlLines.push('');
}

sqlLines.push('COMMIT;');
sqlLines.push('');

const sqlPath = path.join(projectRoot, 'supabase', 'seed.sql');
fs.writeFileSync(sqlPath, sqlLines.join('\n'), 'utf-8');
console.log(`Wrote ${sqlPath} (${(fs.statSync(sqlPath).size / 1024).toFixed(1)} KB)`);
console.log('Build complete!');
